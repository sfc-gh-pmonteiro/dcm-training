-- Data quality expectations (DMF attachments). Evaluated on TRIGGER_ON_CHANGES and
-- on demand with EXECUTE DCM PROJECT ... TEST ALL (TEST is preview).

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT
    TO TABLE ORDERS{{env_suffix}}.RAW.ORDERS
    ON (ORDER_ID)
    EXPECTATION NO_NULL_ORDER_IDS (value = 0);

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT
    TO TABLE ORDERS{{env_suffix}}.RAW.ORDERS
    ON (ORDER_ID)
    EXPECTATION UNIQUE_ORDER_IDS (value = 0);

ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.MIN
    TO TABLE ORDERS{{env_suffix}}.RAW.ORDERS
    ON (AMOUNT)
    EXPECTATION NON_NEGATIVE_AMOUNT (value >= 0);
