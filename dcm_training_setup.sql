/* =============================================================================
   DCM TRAINING - ONE-TIME SETUP (run BEFORE the session, from the command line)

     cd <training folder>
     snow sql -c <connection> -f dcm_training_setup.sql -D "root=$PWD"

   What it does (safe to re-run, nothing is deployed):
     1. Creates the platform container DCM_TRAINING.PROJECTS, a stage for the
        project sources and a small warehouse.
     2. Creates one deployer (owner) role per environment + an auditor role,
        and grants them to YOU (training shortcut - in production only CI
        service users get the QA/PRD deployer roles).
     3. Creates the three DCM project objects ORDERS_DEV / ORDERS_QA / ORDERS_PRD.
     4. Uploads both project versions to the stage:
          release-1.0  <- orders_project_1-0  (before the feature)
          release-1.1  <- orders_project_1-1             (after the feature)

   Requires: ACCOUNTADMIN, Snowflake CLI >= 3.24.0.
   ============================================================================= */

-- ---------------------------------------------------------------- 1. container
USE ROLE ACCOUNTADMIN;
CREATE DATABASE  IF NOT EXISTS DCM_TRAINING COMMENT = 'Holds DCM project objects for the training';
CREATE SCHEMA    IF NOT EXISTS DCM_TRAINING.PROJECTS;
CREATE STAGE     IF NOT EXISTS DCM_TRAINING.PROJECTS.SOURCES
    DIRECTORY = (ENABLE = TRUE)
    COMMENT = 'Project sources (manifest + definitions) per release';
CREATE WAREHOUSE IF NOT EXISTS DCM_TRAINING_WH
    WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- ---------------------------------------------------------------- 2. roles
CREATE ROLE IF NOT EXISTS DCM_DEVELOPER     COMMENT = 'Owns DEV + sandbox DCM projects';
CREATE ROLE IF NOT EXISTS DCM_QA_DEPLOYER   COMMENT = 'Owns the QA DCM project (CI service user)';
CREATE ROLE IF NOT EXISTS DCM_PROD_DEPLOYER COMMENT = 'Owns the PRD DCM project (CI service user only in real life)';
CREATE ROLE IF NOT EXISTS DCM_AUDITOR       COMMENT = 'READ + MONITOR on all projects, cannot deploy';

GRANT CREATE DATABASE, CREATE WAREHOUSE, CREATE ROLE, EXECUTE TASK, EXECUTE DATA METRIC FUNCTION
    ON ACCOUNT TO ROLE DCM_DEVELOPER;
GRANT CREATE DATABASE, CREATE WAREHOUSE, CREATE ROLE, EXECUTE TASK, EXECUTE DATA METRIC FUNCTION
    ON ACCOUNT TO ROLE DCM_QA_DEPLOYER;
GRANT CREATE DATABASE, CREATE WAREHOUSE, CREATE ROLE, EXECUTE TASK, EXECUTE DATA METRIC FUNCTION
    ON ACCOUNT TO ROLE DCM_PROD_DEPLOYER;
GRANT DATABASE ROLE SNOWFLAKE.DATA_METRIC_USER TO ROLE DCM_DEVELOPER;
GRANT DATABASE ROLE SNOWFLAKE.DATA_METRIC_USER TO ROLE DCM_QA_DEPLOYER;
GRANT DATABASE ROLE SNOWFLAKE.DATA_METRIC_USER TO ROLE DCM_PROD_DEPLOYER;

GRANT USAGE ON DATABASE DCM_TRAINING        TO ROLE DCM_DEVELOPER;
GRANT USAGE ON DATABASE DCM_TRAINING        TO ROLE DCM_QA_DEPLOYER;
GRANT USAGE ON DATABASE DCM_TRAINING        TO ROLE DCM_PROD_DEPLOYER;
GRANT USAGE ON DATABASE DCM_TRAINING        TO ROLE DCM_AUDITOR;
GRANT USAGE ON SCHEMA DCM_TRAINING.PROJECTS TO ROLE DCM_DEVELOPER;
GRANT USAGE ON SCHEMA DCM_TRAINING.PROJECTS TO ROLE DCM_QA_DEPLOYER;
GRANT USAGE ON SCHEMA DCM_TRAINING.PROJECTS TO ROLE DCM_PROD_DEPLOYER;
GRANT USAGE ON SCHEMA DCM_TRAINING.PROJECTS TO ROLE DCM_AUDITOR;
GRANT CREATE DCM PROJECT ON SCHEMA DCM_TRAINING.PROJECTS TO ROLE DCM_DEVELOPER;
GRANT CREATE DCM PROJECT ON SCHEMA DCM_TRAINING.PROJECTS TO ROLE DCM_QA_DEPLOYER;
GRANT CREATE DCM PROJECT ON SCHEMA DCM_TRAINING.PROJECTS TO ROLE DCM_PROD_DEPLOYER;
-- The CLI uploads local files to a temporary stage in this schema.
GRANT CREATE STAGE ON SCHEMA DCM_TRAINING.PROJECTS TO ROLE DCM_DEVELOPER;
GRANT CREATE STAGE ON SCHEMA DCM_TRAINING.PROJECTS TO ROLE DCM_QA_DEPLOYER;
GRANT CREATE STAGE ON SCHEMA DCM_TRAINING.PROJECTS TO ROLE DCM_PROD_DEPLOYER;
GRANT READ, WRITE ON STAGE DCM_TRAINING.PROJECTS.SOURCES TO ROLE DCM_DEVELOPER;
GRANT READ ON STAGE DCM_TRAINING.PROJECTS.SOURCES        TO ROLE DCM_QA_DEPLOYER;
GRANT READ ON STAGE DCM_TRAINING.PROJECTS.SOURCES        TO ROLE DCM_PROD_DEPLOYER;
GRANT USAGE ON WAREHOUSE DCM_TRAINING_WH TO ROLE DCM_DEVELOPER;
GRANT USAGE ON WAREHOUSE DCM_TRAINING_WH TO ROLE DCM_QA_DEPLOYER;
GRANT USAGE ON WAREHOUSE DCM_TRAINING_WH TO ROLE DCM_PROD_DEPLOYER;
GRANT USAGE ON WAREHOUSE DCM_TRAINING_WH TO ROLE DCM_AUDITOR;

GRANT ROLE DCM_DEVELOPER     TO ROLE SYSADMIN;
GRANT ROLE DCM_QA_DEPLOYER   TO ROLE SYSADMIN;
GRANT ROLE DCM_PROD_DEPLOYER TO ROLE SYSADMIN;
GRANT ROLE DCM_AUDITOR       TO ROLE SYSADMIN;

-- Training shortcut: the instructor can act as every environment's deployer.
SET me = CURRENT_USER();
GRANT ROLE DCM_DEVELOPER     TO USER IDENTIFIER($me);
GRANT ROLE DCM_QA_DEPLOYER   TO USER IDENTIFIER($me);
GRANT ROLE DCM_PROD_DEPLOYER TO USER IDENTIFIER($me);
GRANT ROLE DCM_AUDITOR       TO USER IDENTIFIER($me);

-- ---------------------------------------------------------------- 3. project objects
USE WAREHOUSE DCM_TRAINING_WH;
USE ROLE DCM_DEVELOPER;
CREATE DCM PROJECT IF NOT EXISTS DCM_TRAINING.PROJECTS.ORDERS_DEV COMMENT = 'Orders - DEV';
GRANT READ, MONITOR ON DCM PROJECT DCM_TRAINING.PROJECTS.ORDERS_DEV TO ROLE DCM_AUDITOR;
USE ROLE DCM_QA_DEPLOYER;
CREATE DCM PROJECT IF NOT EXISTS DCM_TRAINING.PROJECTS.ORDERS_QA  COMMENT = 'Orders - QA';
GRANT READ, MONITOR ON DCM PROJECT DCM_TRAINING.PROJECTS.ORDERS_QA  TO ROLE DCM_AUDITOR;
USE ROLE DCM_PROD_DEPLOYER;
CREATE DCM PROJECT IF NOT EXISTS DCM_TRAINING.PROJECTS.ORDERS_PRD COMMENT = 'Orders - PRD';
GRANT READ, MONITOR ON DCM PROJECT DCM_TRAINING.PROJECTS.ORDERS_PRD TO ROLE DCM_AUDITOR;

-- ---------------------------------------------------------------- 4. upload sources
USE ROLE DCM_DEVELOPER;
PUT 'file://<% root %>/orders_project_1-0/manifest.yml'              @DCM_TRAINING.PROJECTS.SOURCES/release-1.0/                     AUTO_COMPRESS = FALSE OVERWRITE = TRUE;
PUT 'file://<% root %>/orders_project_1-0/sources/definitions/*.sql' @DCM_TRAINING.PROJECTS.SOURCES/release-1.0/sources/definitions/ AUTO_COMPRESS = FALSE OVERWRITE = TRUE;
PUT 'file://<% root %>/orders_project_1-0/sources/macros/*.sql'      @DCM_TRAINING.PROJECTS.SOURCES/release-1.0/sources/macros/      AUTO_COMPRESS = FALSE OVERWRITE = TRUE;
PUT 'file://<% root %>/orders_project_1-1/manifest.yml'                         @DCM_TRAINING.PROJECTS.SOURCES/release-1.1/                     AUTO_COMPRESS = FALSE OVERWRITE = TRUE;
PUT 'file://<% root %>/orders_project_1-1/sources/definitions/*.sql'            @DCM_TRAINING.PROJECTS.SOURCES/release-1.1/sources/definitions/ AUTO_COMPRESS = FALSE OVERWRITE = TRUE;
PUT 'file://<% root %>/orders_project_1-1/sources/macros/*.sql'                 @DCM_TRAINING.PROJECTS.SOURCES/release-1.1/sources/macros/      AUTO_COMPRESS = FALSE OVERWRITE = TRUE;

-- ---------------------------------------------------------------- verify
-- Expect 3 projects and 18 files (2 manifests, 14 definitions, 2 macros).
SHOW DCM PROJECTS IN SCHEMA DCM_TRAINING.PROJECTS;
LIST @DCM_TRAINING.PROJECTS.SOURCES;
